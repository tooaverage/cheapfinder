/* Builds the bookmarklet from the shared extension modules.
 * Outputs:
 *   bookmarklet/cheapfinder.js        — readable bundle (also loadable via CDN)
 *   bookmarklet/install.html          — open on any device, copy/drag the link
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { minify } from "terser";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const SOURCES = [
  "extension/shared/extract.js",
  "extension/shared/heuristics.js",
  "extension/shared/sites.js",
  "extension/shared/ui.js",
  "bookmarklet/main.js"
];

const bundle =
  "/* CheapFinder bookmarklet bundle — generated by tools/build-bookmarklet.mjs. Do not edit. */\n" +
  "(function(){\n" +
  SOURCES.map((p) => readFileSync(join(root, p), "utf8")).join("\n") +
  "\n})();\n";

writeFileSync(join(root, "bookmarklet/cheapfinder.js"), bundle);

const minified = await minify(bundle, {
  compress: { passes: 2 },
  mangle: true,
  format: { comments: false }
});
if (minified.error) throw minified.error;
const slim = minified.code;
new Function(slim); // build-time syntax smoke check on what actually ships

const href = "javascript:" + encodeURIComponent(slim);

const page = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Install CheapFinder bookmarklet</title>
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
         max-width: 640px; margin: 40px auto; padding: 0 20px; background: #14161b; color: #e8eaed; line-height: 1.55; }
  h1 { font-size: 22px; } h1 span { color: #5b8cff; }
  h2 { font-size: 16px; margin-top: 28px; }
  a.bm { display: inline-block; background: #5b8cff; color: #fff; font-weight: 700;
         padding: 10px 18px; border-radius: 10px; text-decoration: none; margin: 8px 0; }
  button { background: #2a2d38; color: #e8eaed; border: 1px solid #34384a; border-radius: 8px;
           padding: 8px 14px; cursor: pointer; font-size: 14px; }
  button:hover { border-color: #5b8cff; }
  ol li { margin: 6px 0; }
  .muted { color: #9aa0a6; font-size: 13px; }
  code { background: #22242c; padding: 2px 6px; border-radius: 5px; font-size: 12.5px; }
</style>
</head>
<body>
  <h1>Cheap<span>Finder</span> — bookmarklet install</h1>
  <p>One bookmark, works in mobile Safari, mobile Chrome and any desktop browser.
     On a product page, tap the bookmark → the CheapFinder panel appears with
     drop-ship signals and price-search shortcuts. Tap again to dismiss.</p>

  <h2>Desktop</h2>
  <p>Drag this to your bookmarks bar:</p>
  <p><a class="bm" href="${href.replace(/"/g, "&quot;")}">💸 CheapFinder</a></p>

  <h2>iPhone / Android</h2>
  <ol>
    <li>Tap the button below to copy the code.</li>
    <li>Bookmark <em>any</em> page (Share → Add Bookmark) and name it <code>CheapFinder</code>.</li>
    <li>Edit that bookmark and replace its URL by pasting the copied code.</li>
    <li>On a product page: open bookmarks, tap <code>CheapFinder</code>.</li>
  </ol>
  <p><button id="copy">Copy bookmarklet code</button> <span id="ok" class="muted"></span></p>
  <p class="muted">Tip: if you use Chrome sync or iCloud, install once on desktop and the
     bookmark syncs to your phone automatically.</p>

  <textarea id="code" style="position:absolute;left:-9999px">${href
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")}</textarea>
  <script>
    var btn = document.getElementById("copy");
    btn.addEventListener("click", function () {
      var ta = document.getElementById("code");
      var ok = document.getElementById("ok");
      function fallbackCopy() {
        ta.style.position = "static";
        ta.focus();
        ta.setSelectionRange(0, ta.value.length); // iOS Safari needs this, select() is not enough
        var copied = false;
        try { copied = document.execCommand("copy"); } catch (e) {}
        ta.style.position = "absolute";
        return copied;
      }
      var p = navigator.clipboard && navigator.clipboard.writeText
        ? navigator.clipboard.writeText(ta.value).then(function () { return true; }, fallbackCopy)
        : Promise.resolve(fallbackCopy());
      p.then(function (copied) {
        ok.textContent = copied ? "Copied ✓" : "Copy failed — tap the code below and copy manually";
        if (!copied) { ta.style.position = "static"; ta.style.width = "100%"; ta.rows = 6; }
      });
    });
  </script>
</body>
</html>
`;

writeFileSync(join(root, "bookmarklet/install.html"), page);
console.log(
  "Built bookmarklet: bundle %d KB, encoded URL %d KB",
  Math.round(slim.length / 1024),
  Math.round(href.length / 1024)
);
